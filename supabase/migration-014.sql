-- 内容:
--   ランキング公開の集計期間を「直近Nか月」ではなく、運営がカレンダーで選んだ
--   開始日・終了日そのもので決められるようにする。
--
--   period_months は残す（過去に公開したスナップショットの表示に使うため）。
--   このアプリはこれ以降 period_months に書き込まなくなるだけで、列自体は消さない。
