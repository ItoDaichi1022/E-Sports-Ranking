-- 差分適用スクリプト 020
--
-- 既に schema.sql（＋002〜019）を実行済みのプロジェクトに、あとから入った
-- 変更だけを当てる。Supabaseダッシュボードの SQL Editor に貼り付けて「Run」。
-- 何度実行しても同じ結果になる。
--
-- 新しくプロジェクトを作る場合はこれは不要（schema.sql に取り込み済み）。
--
-- 内容:
--   配信台が未定でも回戦を開始できるようにする。
--
--   011 では「開始の前に配信台（＝配信に乗せる試合）を決めなければならない」を
--   テーブルのCHECK制約（rounds_stream_before_start）で保証していた。
--   だが配信を伴わない大会や、序盤だけ配信しない大会では、決める配信台が
--   そもそも無い。運営が回戦を開始できず、選手はゲームカウントを入力できない。
--
--   配信台は「決まっていれば選手に伝える」ためのもので、進行の前提ではない。
--   制約を外して、未定のままでも開始できるようにする。
--
--   開始できるのが運営だけである点（RLSの rounds_write）と、開始するまで
--   選手が入力できない点（round_is_started）は今までどおり変わらない。
-- ============================================================================

alter table tournament_rounds
  drop constraint if exists rounds_stream_before_start;
