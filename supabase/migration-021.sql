-- 差分適用スクリプト 021
--
-- 既に schema.sql（＋002〜020）を実行済みのプロジェクトに、あとから入った
-- 変更だけを当てる。Supabaseダッシュボードの SQL Editor に貼り付けて「Run」。
-- 何度実行しても同じ結果になる。
--
-- 新しくプロジェクトを作る場合はこれは不要（schema.sql に取り込み済み）。
--
-- 内容:
--   エントリーの締切時刻（tournaments.entry_deadline）。
--
--   開催日（date）はあっても「いつまでにエントリーすればよいか」がどこにも無く、
--   運営はルール欄に書き、選手はそれを読むしかなかった。募集ページに掲げられる
--   場所を1つ作って、残り時間まで出せるようにする。
--
--   【自動では締め切らない】この時刻を過ぎてもDB側では何も起きない。エントリーは
--   受け付けたままで、締め切ってブラケットを作るのは運営が押したときだけ
--   （js/entries.js の closeRecruitmentAndStart）。時刻はその判断材料と、
--   選手に見せる目安として持つ。
--
--   日付ではなく timestamptz なのは時刻に意味があるため。画面では見る人の
--   地域時刻に直して出す（js/entries.js の entryDeadlineText）。
-- ============================================================================

alter table tournaments
  add column if not exists entry_deadline timestamptz;
