-- 差分適用スクリプト 013
--
-- 既に schema.sql（＋002〜012）を実行済みのプロジェクトに、あとから入った
-- 変更だけを当てる。Supabaseダッシュボードの SQL Editor に貼り付けて「Run」。
-- 何度実行しても同じ結果になる。
--
-- 新しくプロジェクトを作る場合はこれは不要（schema.sql に取り込み済み）。
--
-- 内容:
--   ログアウト状態（ゲスト）でサイトを開くと、データの読み込みが
--   「承認待ちの結果の読み込みの権限がありません（42501）」で失敗する不具合の修正。
--
--   match_result_reports と match_room_codes の select ポリシーは anon にも
--   適用されるが、ポリシーの中で呼ぶ is_match_participant() の実行権限を
--   anon から取り上げていたため、ゲストの select はポリシーの評価の時点で
--   権限エラーになっていた（行が0件になるのではなく、読み込み自体が失敗する）。
--
--   この関数は security definer で、ログインしていなければ常に偽を返すだけ
--   （current_player_id() が null になり、どの試合の当事者にもならない）。
--   anon に実行を許可しても、ゲストに見えるデータは増えない。
-- ============================================================================

grant execute on function is_match_participant(uuid, uuid) to anon;
