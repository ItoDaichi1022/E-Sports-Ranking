-- 既に schema.sql（＋002〜016）を実行済みのプロジェクトに、あとから入った
-- 変更だけを当てる。Supabaseダッシュボードの SQL Editor に貼り付けて「Run」。
-- 何度実行しても同じ結果になる。
--
-- 新しくプロジェクトを作る場合はこれは不要（schema.sql に取り込み済み）。
--
-- 内容:
--   ランキングに反映させるかどうかを、運営が大会ごとに選べるようにする。
--
--   これまでランキングへの反映は条件（参加16人以上・対戦方法が1v1／リレー）だけで
--   決まり、条件を満たした大会は必ず反映されていた。エキシビションや練習会のように
--   「条件は満たすが順位に混ぜたくない」大会が作れなかったため、運営の意思を
--   1つの列として持たせる。反映されるのは
--     ① ranking_opt_in が真
--     ② 参加人数が16人以上
--     ③ 対戦方法が 1v1 またはリレー
--   の3つすべてを満たす大会（判定は js/rankingEligibility.js）。
--
--   既定は真。既に作られている大会はこれまでどおり条件だけで決まる
--   （この列が入ったせいで、過去の大会が黙って対象外になることは無い）。
--   あとから大会情報の編集で切り替えられる。切り替えても公開済みのランキングは
--   作り直されない ── 公開済みのものは集計時点の写しなので、次にランキングを
--   作成したときから反映される（対戦方法を直したときと同じ振る舞い）。
-- ============================================================================

alter table tournaments
  add column if not exists ranking_opt_in boolean not null default true;
